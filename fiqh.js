/* =========================================================
   STATE
========================================================= */

let currentCategory = "All";
let currentSearch = "";


/* =========================================================
   CATEGORY RENDERING
========================================================= */

function renderCategories() {

    if (!categoryButtons) return;

    const categories = [
        "All",
        ...new Set(
            fiqhData.map(
                topic => topic.category
            )
        )
    ];

    categoryButtons.innerHTML = "";

    categories.forEach(category => {

        const button =
            document.createElement("button");

        button.type = "button";

        button.className =
            "category-button";

        button.textContent =
            category;

        if (
            category === currentCategory
        ) {
            button.classList.add("active");
        }

        button.addEventListener(
            "click",
            () => {

                currentCategory =
                    category;

                renderCategories();
                renderTopics();

            }
        );

        categoryButtons.appendChild(
            button
        );

    });

}


/* =========================================================
   GET FILTERED TOPICS
========================================================= */

function getTopics() {

    return fiqhData.filter(topic => {

        const categoryMatch =
            currentCategory === "All" ||
            topic.category === currentCategory;

        const searchableText = [

            topic.title,
            topic.description,
            topic.category

        ]
            .join(" ")
            .toLowerCase();

        const searchMatch =
            currentSearch === "" ||
            searchableText.includes(
                currentSearch
            );

        return (
            categoryMatch &&
            searchMatch
        );

    });

}


/* =========================================================
   RENDER TOPICS
========================================================= */

function renderTopics() {

    if (!fiqhList) return;

    const topics =
        getTopics();

    fiqhList.innerHTML = "";

    if (topics.length === 0) {

        fiqhList.classList.add("hidden");

        noResults?.classList.remove(
            "hidden"
        );

        return;
    }

    fiqhList.classList.remove(
        "hidden"
    );

    noResults?.classList.add(
        "hidden"
    );


    topics.forEach(topic => {

        const card =
            document.createElement("article");

        card.className =
            "fiqh-card";

        card.setAttribute(
            "data-topic-id",
            topic.id
        );

        card.innerHTML = `

            <div class="fiqh-card-icon">
                ${topic.icon}
            </div>

            <h3>
                ${topic.title}
            </h3>

            <p>
                ${topic.description}
            </p>

            <span class="fiqh-card-category">
                ${topic.category}
            </span>

        `;

        card.addEventListener(
            "click",
            () => openTopic(topic.id)
        );

        fiqhList.appendChild(
            card
        );

    });

}


/* =========================================================
   OPEN TOPIC
========================================================= */

function openTopic(id) {

    const topic =
        fiqhData.find(
            item => item.id === id
        );

    if (!topic) return;


    if (readerCategory) {
        readerCategory.textContent =
            topic.category;
    }

    if (readerTitle) {
        readerTitle.textContent =
            topic.title;
    }

    if (readerIntro) {
        readerIntro.textContent =
            topic.intro;
    }

    if (readerContent) {
        readerContent.innerHTML =
            topic.content;
    }


    fiqhList?.classList.add(
        "hidden"
    );

    noResults?.classList.add(
        "hidden"
    );

    document
        .querySelector(".category-section")
        ?.classList.add("hidden");

    document
        .querySelector(".fiqh-search-section")
        ?.classList.add("hidden");

    document
        .querySelector(".fiqh-hero")
        ?.classList.add("hidden");


    fiqhReader?.classList.remove(
        "hidden"
    );


    window.scrollTo({
        top: 0,
        behavior: "smooth"
    });

}


/* =========================================================
   CLOSE READER
========================================================= */

function closeReader() {

    fiqhReader?.classList.add(
        "hidden"
    );

    document
        .querySelector(".category-section")
        ?.classList.remove("hidden");

    document
        .querySelector(".fiqh-search-section")
        ?.classList.remove("hidden");

    document
        .querySelector(".fiqh-hero")
        ?.classList.remove("hidden");


    renderCategories();
    renderTopics();


    window.scrollTo({
        top: 0,
        behavior: "smooth"
    });

}


backToTopics?.addEventListener(
    "click",
    closeReader
);


/* =========================================================
   SEARCH
========================================================= */

searchInput?.addEventListener(
    "input",
    event => {

        currentSearch =
            event.target.value
                .trim()
                .toLowerCase();

        renderTopics();

    }
);


/* =========================================================
   CLEAR SEARCH
========================================================= */

clearSearch?.addEventListener(
    "click",
    () => {

        if (!searchInput) return;

        searchInput.value = "";

        currentSearch = "";

        renderTopics();

        searchInput.focus();

    }
);


