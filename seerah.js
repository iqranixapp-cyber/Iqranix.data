const chapterList = document.getElementById("chapterList");

function renderChapters(list = seerahChapters) {
    chapterList.innerHTML = "";

    list.forEach(chapter => {
        const card = document.createElement("article");

        card.className = "chapter-card";

        card.innerHTML = `
            <button class="chapter-card-button" type="button">
                <span class="chapter-number">
                    ${String(chapter.id).padStart(2, "0")}
                </span>

                <span class="chapter-info">
                    <small>CHAPTER ${String(chapter.id).padStart(2, "0")}</small>
                    <strong>${chapter.title}</strong>
                    <span>${chapter.subtitle}</span>
                </span>

                <span class="chapter-arrow">→</span>
            </button>
        `;

        card.querySelector("button").addEventListener("click", () => {
            openChapter(chapter.id);
        });

        chapterList.appendChild(card);
    });
}

function openChapter(id) {
    const chapter = seerahChapters.find(c => c.id === id);

    if (!chapter) return;

    document.getElementById("readerChapterNumber").textContent =
        `CHAPTER ${chapter.id}`;

    document.getElementById("readerTitle").textContent =
        chapter.title;

    document.getElementById("readerSubtitle").textContent =
        chapter.subtitle;

    document.getElementById("readerContent").innerHTML =
        chapter.content;

    document.getElementById("lessonsContent").innerHTML =
        chapter.lessons
            .map(lesson => `<p>• ${lesson}</p>`)
            .join("");

    document.getElementById("sourcesContent").innerHTML =
        chapter.sources
            .map(source => `<p>📚 ${source}</p>`)
            .join("");

    document.getElementById("chaptersSection").classList.add("hidden");
    document.getElementById("seerahReader").classList.remove("hidden");

    window.scrollTo({
        top: 0,
        behavior: "smooth"
    });
}

document.getElementById("backToChapters").addEventListener("click", () => {
    document.getElementById("seerahReader").classList.add("hidden");
    document.getElementById("chaptersSection").classList.remove("hidden");
});

renderChapters();